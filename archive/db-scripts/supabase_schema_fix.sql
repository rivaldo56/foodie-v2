-- 1. Ensure ChefOnboarding table has the correct structure
-- The crash was caused by 'status' vs 'identity_verification_status' mismatch.

CREATE TABLE IF NOT EXISTS public.chefs_chefonboarding (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES auth.users(id) DEFERRABLE INITIALLY DEFERRED, -- Assuming linked to auth.users or public.users
    culinary_paths jsonb NULL DEFAULT '[]'::jsonb,
    specialties jsonb NULL DEFAULT '[]'::jsonb,
    experience_level character varying(50) NULL,
    portfolio_media jsonb NULL DEFAULT '[]'::jsonb,
    availability_options jsonb NULL DEFAULT '[]'::jsonb,
    pricing_tier character varying(50) NULL,
    certifications jsonb NULL DEFAULT '[]'::jsonb,
    identity_verification_status character varying(20) NOT NULL DEFAULT 'pending',
    completed boolean NOT NULL DEFAULT false,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT chefs_chefonboarding_user_id_key UNIQUE (user_id)
);

