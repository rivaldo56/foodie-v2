-- ============================================================================
-- Foodie v2 - Supabase Client & Business Account Schema
-- ============================================================================
-- This schema integrates Supabase Auth (UUID-based users) with Django backend
-- Supports both B2C (individual clients) and B2B (business accounts)
-- Execute this in: Supabase SQL Editor
-- ============================================================================

-- ============================================================================
-- 1. EXTENSIONS
-- ============================================================================

-- Enable UUID generation (should already be enabled with Supabase Auth)
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ============================================================================
-- 2. CLIENT PROFILE TABLE
-- ============================================================================
-- Purpose: Extend Supabase authenticated users into "clients" 
-- who can make bookings and have preferences
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.clients_clientprofile (
    -- Primary key is the user's UUID from auth.users
    user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    
    -- Profile & Preferences
    dietary_preferences jsonb DEFAULT '[]'::jsonb,
    allergies jsonb DEFAULT '[]'::jsonb,
    preferred_cuisines jsonb DEFAULT '[]'::jsonb,
    
    -- Location
    address text,
    city varchar(100),
    state varchar(100),
    zip_code varchar(20),
    
    -- Emergency Contact
    emergency_contact varchar(100),
    emergency_phone varchar(17),
    
    -- Analytics (rolled up from bookings)
    total_bookings integer DEFAULT 0 NOT NULL,
    total_spend numeric(12, 2) DEFAULT 0.00 NOT NULL,
    last_booking_date timestamptz,
    
    -- Timestamps
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_clientprofile_city ON public.clients_clientprofile(city);
CREATE INDEX IF NOT EXISTS idx_clientprofile_last_booking ON public.clients_clientprofile(last_booking_date DESC);

-- ============================================================================
-- 3. BUSINESS ACCOUNTS TABLE
-- ============================================================================
-- Purpose: Represent companies/organizations that can make bookings
-- Note: Uses bigint PK (not UUID) - is an independent entity, not a user
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.business_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Company Information
    company_name varchar(200) NOT NULL,
    business_email varchar(254) NOT NULL,
    phone_number varchar(17),
    
    -- Address
    address text,
    city varchar(100),
    state varchar(100),
    zip_code varchar(20),
    
    -- Business Details
    tax_id varchar(50),
    billing_address text,
    
    -- Verification
    is_verified boolean DEFAULT false NOT NULL,
    verification_status varchar(20) DEFAULT 'pending' NOT NULL,
    
    -- Analytics
    total_bookings integer DEFAULT 0 NOT NULL,
    total_spend numeric(12, 2) DEFAULT 0.00 NOT NULL,
    
    -- Timestamps
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    
    -- Constraints
    CONSTRAINT verification_status_check CHECK (
        verification_status IN ('pending', 'verified', 'rejected')
    )
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_business_company_name ON public.business_accounts(company_name);
CREATE INDEX IF NOT EXISTS idx_business_email ON public.business_accounts(business_email);
CREATE INDEX IF NOT EXISTS idx_business_verified ON public.business_accounts(is_verified);

-- ============================================================================
-- 4. BUSINESS MEMBERS JUNCTION TABLE
-- ============================================================================
-- Purpose: Define which users belong to which businesses and their roles
-- This is the authorization backbone for B2B functionality
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.business_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Foreign Keys
    business_id bigint NOT NULL REFERENCES public.business_accounts(id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    
    -- Role & Permissions
    role varchar(20) DEFAULT 'member' NOT NULL,
    
    -- Timestamp
    joined_at timestamptz DEFAULT now() NOT NULL,
    
    -- Constraints
    CONSTRAINT business_members_unique UNIQUE (business_id, user_id),
    CONSTRAINT role_check CHECK (role IN ('owner', 'admin', 'member'))
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_business_members_business ON public.business_members(business_id);
CREATE INDEX IF NOT EXISTS idx_business_members_user ON public.business_members(user_id);
CREATE INDEX IF NOT EXISTS idx_business_members_role ON public.business_members(role);

-- ============================================================================
-- 5. USERS TABLE (Sync with auth.users)
-- ============================================================================
-- Purpose: Mirror essential user data from auth.users for Django compatibility
-- Note: This is a VIEW or separate table that Django uses
-- ============================================================================

-- Option A: Create a view (recommended)
CREATE OR REPLACE VIEW public.users_user AS
SELECT 
    id,
    email,
    created_at,
    updated_at,
    email as username,  -- Django expects username
    raw_user_meta_data->>'first_name' as first_name,
    raw_user_meta_data->>'last_name' as last_name,
    raw_user_meta_data->>'role' as role,
    raw_user_meta_data->>'phone_number' as phone_number,
    raw_user_meta_data->>'profile_picture' as profile_picture,
    COALESCE((raw_user_meta_data->>'is_verified')::boolean, false) as is_verified
FROM auth.users;

-- ============================================================================
-- 6. UPDATE BOOKINGS TABLE
-- ============================================================================
-- Purpose: Support both individual client bookings AND business bookings
-- ============================================================================

-- First, check if bookings table exists, if not create it
CREATE TABLE IF NOT EXISTS public.bookings_booking (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- EITHER client_user_id OR business_id must be set, but NOT both
    client_user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
    business_id bigint REFERENCES public.business_accounts(id) ON DELETE CASCADE,
    
    -- Chef reference (assuming chefs_chefprofile table exists)
    chef_id bigint NOT NULL,
    
    -- Booking Details
    service_type varchar(20) DEFAULT 'personal_meal' NOT NULL,
    booking_date timestamptz NOT NULL,
    duration_hours integer DEFAULT 2 NOT NULL,
    number_of_guests integer DEFAULT 1 NOT NULL,
    
    -- Location
    service_address text NOT NULL,
    service_city varchar(100) NOT NULL,
    service_state varchar(100) NOT NULL,
    service_zip_code varchar(20) NOT NULL,
    
    -- Menu & Preferences
    dietary_requirements jsonb DEFAULT '[]'::jsonb,
    special_requests text,
    
    -- Pricing
    base_price numeric(10, 2) NOT NULL,
    additional_fees numeric(10, 2) DEFAULT 0.00 NOT NULL,
    total_amount numeric(10, 2) NOT NULL,
    
    -- Priority
    is_priority boolean DEFAULT false NOT NULL,
    down_payment_amount numeric(10, 2) DEFAULT 0.00 NOT NULL,
    
    -- Status
    status varchar(20) DEFAULT 'pending' NOT NULL,
    confirmation_code varchar(20) UNIQUE,
    
    -- Notes
    client_notes text,
    chef_notes text,
    admin_notes text,
    
    -- Timestamps
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    confirmed_at timestamptz,
    completed_at timestamptz,
    cancelled_at timestamptz,
    
    -- CRITICAL CONSTRAINT: Must have either client OR business, not both
    CONSTRAINT booking_client_or_business_check CHECK (
        (client_user_id IS NOT NULL AND business_id IS NULL) OR
        (client_user_id IS NULL AND business_id IS NOT NULL)
    ),
    
    CONSTRAINT status_check CHECK (
        status IN ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled', 'refunded')
    ),
    
    CONSTRAINT service_type_check CHECK (
        service_type IN ('personal_meal', 'event_catering', 'cooking_class', 'meal_prep')
    )
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_bookings_client_user ON public.bookings_booking(client_user_id) WHERE client_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_bookings_business ON public.bookings_booking(business_id) WHERE business_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_bookings_chef ON public.bookings_booking(chef_id);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON public.bookings_booking(status);
CREATE INDEX IF NOT EXISTS idx_bookings_date ON public.bookings_booking(booking_date DESC);
CREATE INDEX IF NOT EXISTS idx_bookings_created ON public.bookings_booking(created_at DESC);

-- ============================================================================
-- 7. UPDATE PAYMENTS TABLE
-- ============================================================================
-- Purpose: Support payments from both individual clients and businesses
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.payments_payment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    
    -- Booking reference
    booking_id bigint REFERENCES public.bookings_booking(id) ON DELETE CASCADE,
    
    -- EITHER client OR business (mirrors booking relationship)
    client_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
    business_id bigint REFERENCES public.business_accounts(id) ON DELETE SET NULL,
    
    -- Payment Details
    amount numeric(10, 2) NOT NULL,
    currency varchar(3) DEFAULT 'KES' NOT NULL,
    payment_method varchar(50) DEFAULT 'mpesa' NOT NULL,
    status varchar(20) DEFAULT 'pending' NOT NULL,
    
    -- External Provider
    transaction_id varchar(100),
    
    -- Platform Fees
    platform_fee numeric(8, 2) DEFAULT 0.00 NOT NULL,
    processing_fee numeric(8, 2) DEFAULT 0.00 NOT NULL,
    chef_payout numeric(10, 2) DEFAULT 0.00 NOT NULL,
    
    -- Metadata
    payment_metadata jsonb DEFAULT '{}'::jsonb,
    failure_reason text,
    
    -- Timestamps
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    processed_at timestamptz,
    
    CONSTRAINT payment_status_check CHECK (
        status IN ('pending', 'processing', 'completed', 'failed', 'cancelled', 'refunded', 'partially_refunded')
    )
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_payments_booking ON public.payments_payment(booking_id);
CREATE INDEX IF NOT EXISTS idx_payments_client ON public.payments_payment(client_id) WHERE client_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_payments_business ON public.payments_payment(business_id) WHERE business_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_payments_status ON public.payments_payment(status);

