-- ============================================================================
-- 8.1 CLIENT PROFILE POLICIES
-- ============================================================================

-- Drop existing policies if any
DROP POLICY IF EXISTS "Users can view own profile" ON public.clients_clientprofile;
DROP POLICY IF EXISTS "Users can update own profile" ON public.clients_clientprofile;
DROP POLICY IF EXISTS "Users can insert own profile" ON public.clients_clientprofile;
DROP POLICY IF EXISTS "Service role full access" ON public.clients_clientprofile;

-- Users can only view their own profile
CREATE POLICY "Users can view own profile" ON public.clients_clientprofile
    FOR SELECT
    USING (auth.uid() = user_id);

-- Users can only update their own profile
CREATE POLICY "Users can update own profile" ON public.clients_clientprofile
    FOR UPDATE
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);

-- Users can insert their own profile
CREATE POLICY "Users can insert own profile" ON public.clients_clientprofile
    FOR INSERT
    WITH CHECK (auth.uid() = user_id);

-- Service role has full access (for Django backend)
CREATE POLICY "Service role full access" ON public.clients_clientprofile
    FOR ALL
    USING (auth.role() = 'service_role');

-- ============================================================================
-- 8.2 BUSINESS ACCOUNTS POLICIES
-- ============================================================================

DROP POLICY IF EXISTS "Members can view their businesses" ON public.business_accounts;
DROP POLICY IF EXISTS "Owners can update business" ON public.business_accounts;
DROP POLICY IF EXISTS "Authenticated can create business" ON public.business_accounts;
DROP POLICY IF EXISTS "Service role full access" ON public.business_accounts;

-- Users can view businesses they are members of
CREATE POLICY "Members can view their businesses" ON public.business_accounts
    FOR SELECT
    USING (
        EXISTS (
            SELECT 1 FROM public.business_members
            WHERE business_members.business_id = business_accounts.id
            AND business_members.user_id = auth.uid()
        )
    );

-- Only owners and admins can update business details
CREATE POLICY "Owners can update business" ON public.business_accounts
    FOR UPDATE
    USING (
        EXISTS (
            SELECT 1 FROM public.business_members
            WHERE business_members.business_id = business_accounts.id
            AND business_members.user_id = auth.uid()
            AND business_members.role IN ('owner', 'admin')
        )
    );

-- Authenticated users can create businesses
CREATE POLICY "Authenticated can create business" ON public.business_accounts
    FOR INSERT
    WITH CHECK (auth.role() = 'authenticated');

-- Service role full access
CREATE POLICY "Service role full access" ON public.business_accounts
    FOR ALL
    USING (auth.role() = 'service_role');

-- ============================================================================
-- 8.3 BUSINESS MEMBERS POLICIES
