-- 9. TRIGGERS FOR AUTOMATIC TIMESTAMP UPDATES
-- ============================================================================

-- Function to update updated_at timestamp
CREATE OR REPLACE FUNCTION update_updated_at_column()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Apply trigger to all tables with updated_at
DROP TRIGGER IF EXISTS update_clientprofile_updated_at ON public.clients_clientprofile;
CREATE TRIGGER update_clientprofile_updated_at
    BEFORE UPDATE ON public.clients_clientprofile
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_business_updated_at ON public.business_accounts;
CREATE TRIGGER update_business_updated_at
    BEFORE UPDATE ON public.business_accounts
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_booking_updated_at ON public.bookings_booking;
CREATE TRIGGER update_booking_updated_at
    BEFORE UPDATE ON public.bookings_booking
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

DROP TRIGGER IF EXISTS update_payment_updated_at ON public.payments_payment;
CREATE TRIGGER update_payment_updated_at
    BEFORE UPDATE ON public.payments_payment
    FOR EACH ROW
    EXECUTE FUNCTION update_updated_at_column();

